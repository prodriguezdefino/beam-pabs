"""
Parses a JSON profile generated by samply (Firefox Profiler format) and an optional
time log to produce a markdown summary. Maps unresolved addresses to Rust function
names using the samply-generated sidecar, categorizes frames by pipeline stage,
and calculates execution metrics per 1M rows.
"""

import json
import gzip
import argparse
import os
import re
from collections import defaultdict
from dataclasses import dataclass, field
from typing import Dict, List, Set, Optional, Tuple, Any

STAGE_PATTERNS = [
  ("Row bytes -> Arrow", ["apache_beam_io_arrow::convert", "apache_beam_io_arrow::array", "apache_beam_io_arrow::schema"]),
  ("Kafka JSON", ["json_io::", "apache_beam_io_json::", "kafka_io::native::codec::", "apache_beam_io_kafka::native::codec::", "serde_json::"]),
  ("Kafka connector", ["kafka_io::native::", "apache_beam_io_kafka::native::"]),
  ("librdkafka", ["rdkafka::", "rdkafka_sys::"]),
  ("Harness data plane", ["apache_beam_harness::", "harness::"]),
  ("Core coders", ["apache_beam_core::coders::", "apache_beam_core::coders", "core::coders::", "beam::coders::", "beam::coders"]),
  ("Core transforms", ["apache_beam_core::transforms::", "apache_beam_core::transforms", "beam::transforms::", "beam::transforms"]),
  ("gRPC / protobuf / TLS", ["tonic::", "h2::", "rustls::", "prost::"]),
  ("Tokio/runtime", ["tokio::"]),
]

# Prefixes of C symbols, which have no `::` path.
C_PREFIXES = [
  ("rd_", "librdkafka"),
  ("crc32c", "librdkafka"),
]

EXACT_MATCHES = {
  "malloc": "Allocation/memcpy",
  "free": "Allocation/memcpy",
  "madvise": "Allocation/memcpy",
  "_platform_memmove": "Allocation/memcpy",
  "mi_malloc": "Allocation/memcpy",
  "mi_free": "Allocation/memcpy",
  "mi_calloc": "Allocation/memcpy",
  "mi_realloc": "Allocation/memcpy",
}

# Leaves of a thread that waits. A sample with one of them did not catch the thread running.
IDLE_FUNCS = {
  "__psynch_cvwait", "kevent", "__semwait_signal", "mach_msg2_trap", "__workq_kernreturn",
  "semaphore_wait_trap", "semaphore_timedwait_trap", "__psynch_mutexwait", "__ulock_wait",
  "__ulock_wait2", "poll", "__select", "epoll_wait", "syscall", "futex_wait",
  "__futex_abstimed_wait_common",
}

@dataclass
class Totals:
  # Samples that caught a thread running, by count. The CPU of the process is in *_cpu_us.
  rust_non_idle_samples: int = 0
  rust_idle_samples: int = 0
  rust_busy_samples: int = 0
  prism_non_idle_samples: int = 0
  prism_idle_samples: int = 0
  rust_cpu_us: int = 0
  prism_cpu_us: int = 0
  func_self_time: Dict[str, int] = field(default_factory=lambda: defaultdict(int))
  stage_self_time: Dict[str, int] = field(default_factory=lambda: defaultdict(int))
  stage_inclusive_time: Dict[str, int] = field(default_factory=lambda: defaultdict(int))

@dataclass
class TimeStats:
  real_time: float = 0.0
  user_time: float = 0.0
  sys_time: float = 0.0
  peak_rss_mb: float = 0.0

def load_profile(path: str) -> Dict[str, Any]:
  if path == "none" or not os.path.exists(path):
    return {}
  with gzip.open(path, 'rt') as f:
    return json.load(f)

def load_symbols(path: str) -> Optional[Dict[str, Any]]:
  if path == "none":
    return None
  syms_path = path.replace('.gz', '.syms.json')
  if os.path.exists(syms_path):
    with open(syms_path, 'r') as f:
      return json.load(f)
  return None

def find_symbol(st: List[Dict[str, Any]], address: int) -> Optional[int]:
  low = 0
  high = len(st) - 1
  best = -1
  while low <= high:
    mid = (low + high) // 2
    if st[mid]['rva'] <= address:
      best = mid
      low = mid + 1
    else:
      high = mid - 1
  if best >= 0:
    sym = st[best]
    if 'size' in sym:
      if address < sym['rva'] + sym['size']:
        return sym['symbol']
    else:
      return sym['symbol']
  return None

def classify(name: str) -> str:
  if name in EXACT_MATCHES:
    return EXACT_MATCHES[name]
  if name.startswith("_xzm_"):
    return "Allocation/memcpy"
  for prefix, stage in C_PREFIXES:
    if name.startswith(prefix):
      return stage
  segments = name.replace('<', '').replace('>', '').replace(' as ', '::').split("::")
  for stage, prefixes in STAGE_PATTERNS:
    for prefix in prefixes:
      parts = prefix.split("::")
      if parts[-1] == "":
        parts.pop()
      if len(segments) >= len(parts) and all(segments[i] == parts[i] for i in range(len(parts))):
        return stage
  return "User code / other crates"

def classify_inclusive(frames: List[str]) -> Set[str]:
  stages = set()
  for name in frames:
    if name in EXACT_MATCHES or name.startswith("_xzm_"):
      stages.add("Allocation/memcpy")
    elif any(name.startswith(prefix) for prefix, _ in C_PREFIXES):
      stages.add(next(stage for prefix, stage in C_PREFIXES if name.startswith(prefix)))
    else:
      segments = name.replace('<', '').replace('>', '').replace(' as ', '::').split("::")
      matched = False
      for stage, prefixes in STAGE_PATTERNS:
        for prefix in prefixes:
          parts = prefix.split("::")
          if parts[-1] == "":
            parts.pop()
          if len(segments) >= len(parts) and all(segments[i] == parts[i] for i in range(len(parts))):
            stages.add(stage)
            matched = True
            break
        if matched:
          break
  return stages

def symbolize(name: str, address: Optional[int], debug_name: Optional[str], code_id: Optional[str], syms: Optional[Dict[str, Any]]) -> str:
  if not name.startswith("0x") or address is None or not syms:
    return name
  for slib in syms.get('data', []):
    if (code_id and slib.get('code_id') == code_id) or slib.get('debug_name') == debug_name:
      st = slib.get('symbol_table', [])
      if st:
        sym_idx = find_symbol(st, address)
        if sym_idx is not None:
          return syms['string_table'][sym_idx]
      break
  return name

def aggregate(prof: Dict[str, Any], syms: Optional[Dict[str, Any]]) -> Totals:
  totals = Totals()
  if not prof:
    return totals

  prism_pids = set()
  for t in prof.get('threads', []):
    process_name = t.get('processName', t.get('name', '')).lower()
    if 'prism' in process_name:
      prism_pids.add(t.get('pid'))

  for t in prof.get('threads', []):
    pid = t.get('pid')
    is_prism = pid in prism_pids

    frameTable = t.get('frameTable') or prof.get('shared', {}).get('frameTable', {})
    funcTable = t.get('funcTable') or prof.get('shared', {}).get('funcTable', {})
    resourceTable = t.get('resourceTable') or prof.get('shared', {}).get('resourceTable', {})
    stackTable = t.get('stackTable') or prof.get('shared', {}).get('stackTable', {})
    stringArray = t.get('stringArray') or t.get('stringTable') or prof.get('shared', {}).get('stringArray') or prof.get('shared', {}).get('stringTable') or []

    samples = t.get('samples', {})
    stack_data = samples.get('stack', [])
    weight_data = samples.get('weight', [])
    if not weight_data:
      weight_data = [1] * len(stack_data)

    cpu_delta_data = samples.get('threadCPUDelta', [])

    for idx, (stack_idx, weight) in enumerate(zip(stack_data, weight_data)):
      if stack_idx is None:
        continue

      delta_us = cpu_delta_data[idx] if idx < len(cpu_delta_data) else 0
      if is_prism:
        totals.prism_cpu_us += delta_us
      else:
        totals.rust_cpu_us += delta_us

      curr = stack_idx
      frames = []

      while curr is not None:
        if curr >= len(stackTable.get('frame', [])):
          break
        f_idx = stackTable['frame'][curr]
        if f_idx >= len(frameTable.get('func', [])):
          break
        func_idx = frameTable['func'][f_idx]
        address = frameTable.get('address', [])[f_idx] if 'address' in frameTable else None

        name = ''
        if func_idx < len(funcTable.get('name', [])):
          name_idx = funcTable['name'][func_idx]
          if name_idx < len(stringArray):
            name = stringArray[name_idx]

        debug_name = None
        code_id = None
        if address is not None and syms and 'resource' in funcTable and func_idx < len(funcTable['resource']):
          res_idx = funcTable['resource'][func_idx]
          if res_idx is not None and 'lib' in resourceTable and res_idx < len(resourceTable['lib']):
            lib_idx = resourceTable['lib'][res_idx]
            if lib_idx is not None and lib_idx < len(prof.get('libs', [])):
              lib_entry = prof['libs'][lib_idx]
              debug_name = lib_entry.get('debugName')
              code_id = lib_entry.get('codeId')

        if debug_name == 'prism-darwin-arm64':
          debug_name = ''

        name = symbolize(name, address, debug_name, code_id, syms)
        frames.append(name)
        curr = stackTable.get('prefix', [])[curr] if 'prefix' in stackTable and curr < len(stackTable['prefix']) else None

      if not frames:
        if is_prism:
          totals.prism_idle_samples += weight
        else:
          totals.rust_idle_samples += weight
        continue

      leaf = frames[0]
      # Count samples, not CPU deltas: a delta puts work done before a wait on the wait frame.
      # A zero delta marks a thread blocked in a call that IDLE_FUNCS does not list.
      cpu_weight = weight
      is_idle = leaf in IDLE_FUNCS or (bool(cpu_delta_data) and delta_us == 0)

      if is_prism:
        if is_idle:
          totals.prism_idle_samples += weight
        else:
          totals.prism_non_idle_samples += cpu_weight
      else:
        if is_idle:
          totals.rust_idle_samples += weight
        else:
          totals.rust_non_idle_samples += cpu_weight
          totals.rust_busy_samples += weight
          totals.func_self_time[leaf] += cpu_weight
          stage = classify(leaf)
          totals.stage_self_time[stage] += cpu_weight

          for inclusive_stage in classify_inclusive(frames):
            totals.stage_inclusive_time[inclusive_stage] += cpu_weight

  return totals

def parse_time_content(content: str) -> Optional[TimeStats]:
  stats = TimeStats()

  # GNU format parsing
  gnu_real_match = re.search(r'^\s*Elapsed \(wall clock\) time \(h:mm:ss or m:ss\):\s*([\d:.]+)', content, re.MULTILINE)
  if gnu_real_match:
    parts = gnu_real_match.group(1).split(':')
    if len(parts) == 2:
      stats.real_time = float(parts[0]) * 60 + float(parts[1])
    elif len(parts) == 3:
      stats.real_time = float(parts[0]) * 3600 + float(parts[1]) * 60 + float(parts[2])
    else:
      stats.real_time = float(parts[0])
  gnu_user_match = re.search(r'^\s*User time \(seconds\):\s*([\d.]+)', content, re.MULTILINE)
  if gnu_user_match:
    stats.user_time = float(gnu_user_match.group(1))
  gnu_sys_match = re.search(r'^\s*System time \(seconds\):\s*([\d.]+)', content, re.MULTILINE)
  if gnu_sys_match:
    stats.sys_time = float(gnu_sys_match.group(1))
  gnu_rss_match = re.search(r'^\s*Maximum resident set size \(kbytes\):\s*(\d+)', content, re.MULTILINE)
  if gnu_rss_match:
    stats.peak_rss_mb = float(gnu_rss_match.group(1)) / 1024.0

  # macOS format parsing
  mac_user_match = re.search(r'^\s*([\d.]+)\s+real\s+([\d.]+)\s+user\s+([\d.]+)\s+sys', content, re.MULTILINE)
  if mac_user_match:
    stats.real_time = float(mac_user_match.group(1))
    stats.user_time = float(mac_user_match.group(2))
    stats.sys_time = float(mac_user_match.group(3))
  mac_rss_match = re.search(r'^\s*(\d+)\s+maximum resident set size', content, re.MULTILINE)
  if mac_rss_match:
    stats.peak_rss_mb = float(mac_rss_match.group(1)) / 1024.0 / 1024.0

  return stats if (stats.user_time > 0 or stats.peak_rss_mb > 0) else None

def parse_time(path: Optional[str]) -> Optional[TimeStats]:
  if not path or not os.path.exists(path):
    return None
  with open(path, 'r') as f:
    content = f.read()
  return parse_time_content(content)

def render(has_prof: bool, has_syms: bool, interval_ms: float, totals: Totals, stats: Optional[TimeStats], rows: Optional[int]):
  if has_prof:
    print("## CPU Breakdown by Stage")
    if not has_syms:
      print("\n> **Note**: No `<profile>.syms.json` sidecar found. Frame names are raw addresses. Provide the sidecar or run `samply record` with `--unstable-presymbolicate` to see Rust function names.\n")

    print("Percentages reflect self-time distribution among categorized non-idle frames in the Rust process.\n")
    print("| Stage | Self CPU % |")
    print("|---|---|")
    for stage, weight in sorted(totals.stage_self_time.items(), key=lambda x: x[1], reverse=True):
      pct = 100.0 * weight / totals.rust_non_idle_samples if totals.rust_non_idle_samples else 0
      print(f"| {stage} | {pct:.1f}% |")

    print("\n## Inclusive % by Stage")
    print("A sample counts once per stage present in its stack. Unmatched fallback stages are excluded.\n")
    print("| Stage | Inclusive CPU % |")
    print("|---|---|")
    for stage, weight in sorted(totals.stage_inclusive_time.items(), key=lambda x: x[1], reverse=True):
      pct = 100.0 * weight / totals.rust_non_idle_samples if totals.rust_non_idle_samples else 0
      print(f"| {stage} | {pct:.1f}% |")

    total_rust = totals.rust_busy_samples + totals.rust_idle_samples
    total_non_idle = totals.rust_non_idle_samples + totals.prism_non_idle_samples

    if total_non_idle > 0:
      prism_pct = 100.0 * totals.prism_non_idle_samples / total_non_idle
      rust_pct = 100.0 * totals.rust_non_idle_samples / total_non_idle
      print(f"\n- **Prism**: {prism_pct:.1f}% of the non-idle CPU")
      print(f"- **Rust**: {rust_pct:.1f}% of the non-idle CPU")

    if total_rust > 0:
      print(f"*(Rust threads were idle in {100.0 * totals.rust_idle_samples / total_rust:.1f}% of their samples)*\n")

    print("## Top 15 Hot Frames (Self Time, Non-Idle)\n")
    print("| Frame | Self CPU % |")
    print("|---|---|")
    for name, weight in sorted(totals.func_self_time.items(), key=lambda x: x[1], reverse=True)[:15]:
      pct = 100.0 * weight / totals.rust_non_idle_samples if totals.rust_non_idle_samples else 0
      display_name = name[:77] + "..." if len(name) > 80 else name
      print(f"| `{display_name}` | {pct:.1f}% |")

  if stats:
    if not has_prof:
      print(f"\n## Profile Execution Metrics")
    else:
      print(f"## Profile Execution Metrics")
    if stats.peak_rss_mb > 0:
      print(f"- **Peak RSS**: {stats.peak_rss_mb:.1f} MB")
    if stats.user_time > 0 or stats.sys_time > 0:
      print(f"- **Real Time**: {stats.real_time:.2f}s")
      print(f"- **Total CPU Time (user+sys)**: {stats.user_time + stats.sys_time:.2f}s (includes waited-for children like Prism)")

  if rows and rows > 0 and has_prof:
    rust_cpu_time_s = (totals.rust_cpu_us / 1e6) if totals.rust_cpu_us > 0 else (totals.rust_non_idle_samples * interval_ms / 1000.0)
    prism_cpu_time_s = (totals.prism_cpu_us / 1e6) if totals.prism_cpu_us > 0 else (totals.prism_non_idle_samples * interval_ms / 1000.0)

    if not stats:
      print(f"\n## Profile Execution Metrics")
    print(f"- **Rows Processed**: {rows:,}")
    print(f"- **Rust CPU Time**: {rust_cpu_time_s:.2f} s")
    print(f"- **Prism CPU Time**: {prism_cpu_time_s:.2f} s")
    print(f"- **CPU Time / 1M rows (Rust only)**: {rust_cpu_time_s / (rows / 1_000_000):.2f} CPU seconds")

def main():
  parser = argparse.ArgumentParser(description="Summarize CPU profiles.")
  parser.add_argument("profile_json", help="Path to samply profile.json.gz (or 'none')")
  parser.add_argument("--time-output", help="Path to time output", default=None)
  parser.add_argument("--rows", type=int, help="Number of rows processed", default=None)
  args = parser.parse_args()

  prof = load_profile(args.profile_json)
  syms = load_symbols(args.profile_json)
  totals = aggregate(prof, syms)
  stats = parse_time(args.time_output)

  has_prof = args.profile_json != "none"
  interval_ms = prof.get('meta', {}).get('interval', 1.0) if has_prof else 1.0

  render(has_prof, bool(syms), interval_ms, totals, stats, args.rows)

if __name__ == "__main__":
  main()
